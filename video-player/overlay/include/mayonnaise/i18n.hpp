inline Language currentLanguage() {
    const char* lang = std::getenv("LC_ALL");
    if (!lang || !*lang) lang = std::getenv("LC_MESSAGES");
    if (!lang || !*lang) lang = std::getenv("LANG");
    if (!lang) return Language::English;
    std::string s(lang);
    if (s.rfind("es", 0) == 0) return Language::Spanish;
    if (s.rfind("it", 0) == 0) return Language::Italian;
    if (s.rfind("fr", 0) == 0) return Language::French;
    return Language::English;
}

